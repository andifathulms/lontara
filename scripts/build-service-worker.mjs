/**
 * Generate out/sw.js after `next build`.
 *
 * PRD §12: fully offline after first load. The site is static, so this needs no
 * runtime strategy cleverness — it needs an accurate precache list, and the only
 * way to get one is to read the export that was actually produced. Next emits
 * content-hashed chunk names, so a hand-written list in public/ would go stale
 * on the next build and fail silently.
 *
 * The cache name is derived from the contents of the export, so a deploy that
 * changes nothing does not invalidate anyone's cache, and a deploy that changes
 * anything invalidates all of it. Per-file revisioning would be smaller over the
 * wire; 1.7 MB total is not worth the complexity of getting it wrong.
 */
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const REPOSITORY_NAME = 'lontara'
const BASE_PATH = `/${REPOSITORY_NAME}`
const ROOT = join(process.cwd(), 'out')

try {
  statSync(ROOT)
} catch {
  console.error('out/ tidak ada. Jalankan `next build` dulu.')
  process.exit(1)
}

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(path))
    else out.push(path)
  }
  return out
}

/** Not precached: the worker itself, and files a browser never requests. */
const SKIP = new Set(['sw.js', '.nojekyll'])

const files = walk(ROOT)
  .map((path) => relative(ROOT, path))
  .filter((rel) => !SKIP.has(rel.split(sep).join('/')))
  .sort()

const urls = files.map((rel) => `${BASE_PATH}/${rel.split(sep).join('/')}`)

/**
 * The critical set must all cache or the install fails loudly. Everything else
 * is best-effort — losing a .txt RSC payload degrades a navigation, whereas
 * losing the aksara font or a JS chunk means a broken app, and an install that
 * "succeeded" without them would be a lie.
 */
const critical = urls.filter(
  (url) => url.endsWith('.html') || url.endsWith('.js') || url.endsWith('.css') || url.endsWith('.woff2'),
)

const version = createHash('sha256')
  .update(files.join('\n'))
  .update(
    files.map((rel) => createHash('sha256').update(readFileSync(join(ROOT, rel))).digest('hex')).join(''),
  )
  .digest('hex')
  .slice(0, 12)

const sw = `/*
 * Generated by scripts/build-service-worker.mjs. Do not edit — it is rebuilt
 * from the export on every build.
 *
 * PRD §12: fully offline after first load.
 *
 * Cache-first, unconditionally. That is correct here and would not be elsewhere:
 * the export is content-hashed, the cache name is derived from the contents of
 * the whole export, and a new build gets a new cache. Nothing inside one version
 * can go stale.
 *
 * No skipWaiting and no clients.claim, deliberately. The app router loads route
 * chunks lazily, so swapping the active worker mid-session could hand an already
 * loaded page chunks from a different build. A new version activates once the
 * last old tab closes, which is slower and cannot produce version skew.
 */
const CACHE = 'lontara-${version}'
const BASE_PATH = ${JSON.stringify(BASE_PATH)}
const OFFLINE_FALLBACK = ${JSON.stringify(`${BASE_PATH}/id/`)}

const PRECACHE = ${JSON.stringify(urls, null, 2)}

const CRITICAL = new Set(${JSON.stringify(critical, null, 2)})

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE)
      const failed = []

      await Promise.all(
        PRECACHE.map(async (url) => {
          try {
            // cache: 'reload' so a stale HTTP cache entry cannot be baked in.
            const response = await fetch(new Request(url, { cache: 'reload' }))
            if (!response.ok) throw new Error(String(response.status))
            await cache.put(url, response)
          } catch (error) {
            failed.push(url)
          }
        }),
      )

      const criticalFailures = failed.filter((url) => CRITICAL.has(url))
      if (criticalFailures.length > 0) {
        // Fail the install rather than report offline readiness we do not have.
        throw new Error('gagal menyimpan berkas penting: ' + criticalFailures.join(', '))
      }
    })(),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys()
      await Promise.all(
        names.filter((name) => name.startsWith('lontara-') && name !== CACHE).map((name) => caches.delete(name)),
      )
    })(),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return

  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return
  if (!url.pathname.startsWith(BASE_PATH)) return

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE)

      // trailingSlash: true, so a directory request resolves to its index.html.
      const candidates = [url.pathname]
      if (url.pathname.endsWith('/')) candidates.push(url.pathname + 'index.html')

      for (const candidate of candidates) {
        const hit = await cache.match(candidate)
        if (hit) return hit
      }

      try {
        return await fetch(request)
      } catch (error) {
        // Offline and not precached. Only a navigation can be usefully
        // recovered; anything else has to fail so the caller sees a real error
        // rather than an HTML page where it expected a chunk.
        if (request.mode === 'navigate') {
          const fallback = await cache.match(OFFLINE_FALLBACK)
          if (fallback) return fallback
        }
        throw error
      }
    })(),
  )
})
`

writeFileSync(join(ROOT, 'sw.js'), sw)

const bytes = urls.reduce((sum, _url, index) => {
  const rel = files[index]
  return sum + (rel ? statSync(join(ROOT, rel)).size : 0)
}, 0)

console.log(`out/sw.js — cache lontara-${version}`)
console.log(`  ${urls.length} berkas diprasimpan, ${critical.length} di antaranya wajib`)
console.log(`  ${(bytes / 1024).toFixed(0)} KiB tanpa kompresi`)
